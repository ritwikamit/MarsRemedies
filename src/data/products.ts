export const createProductSlug = (brandName: string, id: string): string => {
  const clean = brandName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
  return `${clean}-${id}`;
};

export const PRODUCTS: Product[] = RAW_PRODUCTS.map((prod) => ({
  ...prod,
  slug: createProductSlug(prod.brandName, prod.id),
}));

export const getFeaturedProducts = (): Product[] => {
  return PRODUCTS.filter((p) => p.featured);
};

export const getProductBySlug = (slug: string): Product | undefined => {
  return PRODUCTS.find((p) => p.slug === slug || p.id === slug);
};

export const getCategoryStats = (): Record<ProductCategory, number> => {
  const stats = CATEGORIES.reduce((acc, cat) => {
    acc[cat] = 0;
    return acc;
  }, {} as Record<ProductCategory, number>);

  PRODUCTS.forEach((p) => {
    if (stats[p.category] !== undefined) {
      stats[p.category] += 1;
    }
  });

  return stats;
};

